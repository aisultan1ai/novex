"""Язык ответа API: русский (по умолчанию) или казахский.

Как устроено:
* Фронтенд шлёт ``Accept-Language: ru|kk`` с каждым запросом (язык
  страницы, а не браузера; заголовок CORS-safelisted — без лишнего preflight).
  ``X-Locale`` тоже поддерживается и приоритетнее. ``LocaleMiddleware``
  кладёт язык в contextvar.
* Сообщения в коде пишутся по-русски, как и раньше. Обработчики исключений в
  ``main.py`` прогоняют ``detail`` через :func:`translate` — для казахского
  интерфейса известные фразы заменяются переводом, неизвестные остаются как есть.
  Так не нужно трогать сотни ``raise`` по всему коду.
* Для писем и уведомлений, которые уходят вне HTTP-запроса (воркеры), язык
  берётся из ``users.locale`` — см. :func:`user_locale`.

Технические тексты для админов (ответы API перевозчиков, ``pip install``…)
намеренно не переводятся.
"""

from __future__ import annotations

import re
from contextvars import ContextVar
from typing import Literal, NamedTuple

Locale = Literal["ru", "kk"]
SUPPORTED_LOCALES: tuple[Locale, ...] = ("ru", "kk")
DEFAULT_LOCALE: Locale = "ru"
LOCALE_HEADER = "X-Locale"
ACCEPT_LANGUAGE = "Accept-Language"

_current: ContextVar[Locale] = ContextVar("novex_locale", default=DEFAULT_LOCALE)
# True, если язык пришёл явно в заголовке запроса (а не по умолчанию) —
# только тогда синхронизируем его в users.locale.
_explicit: ContextVar[bool] = ContextVar("novex_locale_explicit", default=False)


def normalize_locale(value: str | None) -> Locale | None:
    """'kk', 'kk-KZ', 'kz' → 'kk'; 'ru', 'ru-RU' → 'ru'; иначе None."""
    if not value:
        return None
    tag = value.strip().lower().replace("_", "-").split("-")[0]
    if tag in ("kk", "kz"):
        return "kk"
    if tag == "ru":
        return "ru"
    return None


def locale_from_headers(x_locale: str | None, accept_language: str | None) -> str | None:
    """X-Locale, иначе первый тег Accept-Language ("kk-KZ,kk;q=0.9" → "kk-KZ")."""
    if x_locale:
        return x_locale
    if accept_language:
        return accept_language.split(",")[0].split(";")[0].strip() or None
    return None


def set_request_locale(value: str | None) -> None:
    loc = normalize_locale(value)
    _current.set(loc or DEFAULT_LOCALE)
    _explicit.set(loc is not None)


def current_locale() -> Locale:
    return _current.get()


def locale_is_explicit() -> bool:
    return _explicit.get()


def user_locale(user: object | None) -> Locale:
    """Язык пользователя для писем/уведомлений (колонка users.locale)."""
    return normalize_locale(getattr(user, "locale", None)) or DEFAULT_LOCALE


class Bi(NamedTuple):
    """Текст на двух языках. Нужный выбирается по языку получателя —
    например, NotificationsRepository.create() смотрит users.locale."""

    ru: str
    kk: str

    def for_locale(self, locale: str | None) -> str:
        return self.kk if normalize_locale(locale) == "kk" else self.ru


def resolve(text: str | Bi | None, locale: str | None) -> str | None:
    """str возвращается как есть, Bi — на нужном языке."""
    return text.for_locale(locale) if isinstance(text, Bi) else text


def pick(locale: str | None, ru: str, kk: str) -> str:
    """Выбор текста по языку — для коротких строк прямо в коде."""
    return kk if normalize_locale(locale) == "kk" else ru


