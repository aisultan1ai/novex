_PYDANTIC_PREFIX = "Value error, "


def translate(text: str, locale: str | None = None) -> str:
    """Перевести сообщение на язык запроса (или явно переданный язык)."""
    loc = normalize_locale(locale) if locale else current_locale()
    if loc != "kk" or not isinstance(text, str):
        return text
    prefix = ""
    body = text
    if body.startswith(_PYDANTIC_PREFIX):
        prefix, body = _PYDANTIC_PREFIX, body[len(_PYDANTIC_PREFIX):]
    exact = _KK_EXACT.get(body)
    if exact is not None:
        return prefix + exact
    for pattern, repl in _KK_PATTERNS:
        if pattern.match(body):
            return prefix + pattern.sub(repl, body)
    return text


def translate_detail(detail: object, locale: str | None = None) -> object:
    """detail из ответа об ошибке: строка, {code, message} или список Pydantic-ошибок."""
    if isinstance(detail, str):
        return translate(detail, locale)
    if isinstance(detail, dict) and isinstance(detail.get("message"), str):
        return {**detail, "message": translate(detail["message"], locale)}
    if isinstance(detail, list):
        out = []
        for item in detail:
            if isinstance(item, dict) and isinstance(item.get("msg"), str):
                item = {**item, "msg": translate(item["msg"], locale)}
            out.append(item)
        return out
    return detail
